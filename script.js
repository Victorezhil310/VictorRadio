function loadSavedSignals() {
    try {
        const stored = localStorage.getItem("victor_radio_signals");
        if (stored) state.savedSignals = JSON.parse(stored);
    } catch (e) {}
}

function saveSignalsToStorage() {
    try {
        localStorage.setItem("victor_radio_signals", JSON.stringify(state.savedSignals));
    } catch (e) {}
}

function renderSavedSignals() {
    const container = document.getElementById("savedSignalsList");
    if (!container) return;

    if (state.savedSignals.length === 0) {
        container.innerHTML = "<p style='color:#94A3B8; font-size:12px; padding:12px;'>No saved signal captures in library.</p>";
        return;
    }

    container.innerHTML = state.savedSignals.map(sig => `
        <div class="signal-item">
            <div class="sig-header">
                <span class="sig-title">${sig.title}</span>
                <button class="delete-sig-btn" onclick="deleteSignal('${sig.id}')">✖</button>
            </div>
            <div style="display:flex; justify-content:space-between; align-items:center;">
                <span class="sig-freq">${sig.freqMhz.toFixed(3)} MHz</span>
                <span style="font-size:10px; color:#94A3B8;">${new Date(sig.timestamp).toLocaleTimeString()}</span>
            </div>
            <div class="sig-details">
                <span>Mode: ${sig.mode}</span>
                <span>Peak: ${sig.peakDbm.toFixed(1)} dBm</span>
                <span>SNR: ${sig.snrDb.toFixed(1)} dB</span>
            </div>
        </div>
    `).join("");
}

window.deleteSignal = function(id) {
    state.savedSignals = state.savedSignals.filter(s => s.id !== id);
    saveSignalsToStorage();
    renderSavedSignals();
};

function exportJson() {
    const dataStr = "data:text/json;charset=utf-8," + encodeURIComponent(JSON.stringify(state.savedSignals, null, 2));
    downloadFile(dataStr, "victor_radio_signals.json");
}

function exportCsv() {
    let csv = "Title,FrequencyMHz,PeakDbm,SNRdB,Mode,Timestamp\n";
    state.savedSignals.forEach(s => {
        csv += `"${s.title}",${s.freqMhz},${s.peakDbm},${s.snrDb},"${s.mode}",${s.timestamp}\n`;
    });
    const dataStr = "data:text/csv;charset=utf-8," + encodeURIComponent(csv);
    downloadFile(dataStr, "victor_radio_signals.csv");
}

function downloadFile(dataUri, fileName) {
    const link = document.createElement("a");
    link.setAttribute("href", dataUri);
    link.setAttribute("download", fileName);
    document.body.appendChild(link);
    link.click();
    link.remove();
}
