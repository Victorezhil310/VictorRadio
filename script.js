// Planet Oscilloscope Canvas Visualizer
let planetOscCanvas, planetOscCtx;

function setupPlanetOscilloscope() {
    planetOscCanvas = document.getElementById("planetOscilloscopeCanvas");
    if (!planetOscCanvas) return;
    planetOscCtx = planetOscCanvas.getContext("2d");
    requestAnimationFrame(renderPlanetOscilloscope);
}

function renderPlanetOscilloscope() {
    if (!planetOscCanvas || !planetOscCtx) return;

    const w = planetOscCanvas.width = planetOscCanvas.parentElement.clientWidth;
    const h = planetOscCanvas.height = planetOscCanvas.parentElement.clientHeight;

    planetOscCtx.fillStyle = "#020408";
    planetOscCtx.fillRect(0, 0, w, h);

    if (planetAnalyserNode && state.activePlanetId) {
        const bufferLength = planetAnalyserNode.frequencyBinCount;
        const dataArray = new Uint8Array(bufferLength);
        planetAnalyserNode.getByteTimeDomainData(dataArray);

        planetOscCtx.lineWidth = 2;
        planetOscCtx.strokeStyle = "#00E676";
        planetOscCtx.beginPath();

        const sliceWidth = w / bufferLength;
        let x = 0;

        for (let i = 0; i < bufferLength; i++) {
            const v = dataArray[i] / 128.0;
            const y = (v * h) / 2;
            if (i === 0) planetOscCtx.moveTo(x, y);
            else planetOscCtx.lineTo(x, y);
            x += sliceWidth;
        }
        planetOscCtx.stroke();
    } else {
        planetOscCtx.lineWidth = 1;
        planetOscCtx.strokeStyle = "rgba(148, 163, 184, 0.3)";
        planetOscCtx.beginPath();
        planetOscCtx.moveTo(0, h / 2);
        planetOscCtx.lineTo(w, h / 2);
        planetOscCtx.stroke();
    }

    requestAnimationFrame(renderPlanetOscilloscope);
}

// --- Live Spectrum and Waterfall Visualizer ---
let specCanvas, specCtx, watCanvas, watCtx;
let fftPoints = new Float32Array(256);
let currentPeakDbm = -105;
let currentSnrDb = 0;

function setupCanvas() {
    specCanvas = document.getElementById("spectrumCanvas");
    if (!specCanvas) return;
    specCtx = specCanvas.getContext("2d");

    watCanvas = document.getElementById("waterfallCanvas");
    watCtx = watCanvas.getContext("2d");

    window.addEventListener("resize", resizeCanvases);
    resizeCanvases();

    requestAnimationFrame(renderSpectrumLoop);
}

function resizeCanvases() {
    if (!specCanvas || !watCanvas) return;
    const dpr = window.devicePixelRatio || 1;

    const specRect = specCanvas.parentElement.getBoundingClientRect();
    specCanvas.width = specRect.width * dpr;
    specCanvas.height = specRect.height * dpr;

    const watRect = watCanvas.parentElement.getBoundingClientRect();
    watCanvas.width = watRect.width * dpr;
    watCanvas.height = watRect.height * dpr;
}

function renderSpectrumLoop() {
    if (!specCanvas || !specCtx || !watCanvas || !watCtx) return;

    const specW = specCanvas.width;
    const specH = specCanvas.height;
    const watW = watCanvas.width;
    const watH = watCanvas.height;

    let maxVal = -150;
    let noiseFloorSum = 0;

    for (let i = 0; i < fftPoints.length; i++) {
        let val = -110 + (Math.random() * 6) + (state.gainDb * 0.22);
        const distFromCenter = Math.abs(i - fftPoints.length / 2);
        if (distFromCenter < 12) {
            val += 42 * Math.exp(-Math.pow(distFromCenter / 3.0, 2));
        }
        if (state.notchFilter && distFromCenter < 4) {
            val -= 30;
        }
        fftPoints[i] = val;

        if (val > maxVal) maxVal = val;
        if (distFromCenter > 20) noiseFloorSum += val;
    }

    const avgNoiseFloor = noiseFloorSum / (fftPoints.length - 40);
    currentPeakDbm = maxVal;
    currentSnrDb = Math.max(0, currentPeakDbm - avgNoiseFloor);

    const peakBadge = document.getElementById("peakPowerBadge");
    const snrBadge = document.getElementById("snrBadge");
    if (peakBadge) peakBadge.textContent = `PEAK: ${currentPeakDbm.toFixed(1)} dBm`;
    if (snrBadge) snrBadge.textContent = `SNR: ${currentSnrDb.toFixed(1)} dB`;

    specCtx.fillStyle = "#020408";
    specCtx.fillRect(0, 0, specW, specH);

    specCtx.strokeStyle = "rgba(255, 255, 255, 0.05)";
    specCtx.lineWidth = 1;
    for (let i = 1; i < 10; i++) {
        const x = (specW / 10) * i;
        specCtx.beginPath();
        specCtx.moveTo(x, 0);
        specCtx.lineTo(x, specH);
        specCtx.stroke();
    }

    specCtx.beginPath();
    specCtx.strokeStyle = "#22D3EE";
    specCtx.lineWidth = 2;

    const dx = specW / (fftPoints.length - 1);
    for (let i = 0; i < fftPoints.length; i++) {
        const dbm = fftPoints[i];
        const y = specH - ((dbm + 120) / 100) * specH;
        if (i === 0) specCtx.moveTo(0, y);
        else specCtx.lineTo(i * dx, y);
    }
    specCtx.stroke();

    specCtx.lineTo(specW, specH);
    specCtx.lineTo(0, specH);
    const grad = specCtx.createLinearGradient(0, 0, 0, specH);
    grad.addColorStop(0, "rgba(34, 211, 238, 0.25)");
    grad.addColorStop(1, "rgba(34, 211, 238, 0.0)");
    specCtx.fillStyle = grad;
    specCtx.fill();

    // Waterfall
    const rowHeight = Math.max(2, Math.floor(watH / 60));
    watCtx.drawImage(watCanvas, 0, 0, watW, watH - rowHeight, 0, rowHeight, watW, watH - rowHeight);

    for (let i = 0; i < fftPoints.length; i++) {
        const dbm = fftPoints[i];
        const normalized = Math.max(0, Math.min(1, (dbm + 110) / 70));
        let r = 0, g = 0, b = 0;
        if (normalized < 0.3) {
            b = Math.floor(normalized * 3.3 * 255);
        } else if (normalized < 0.7) {
            g = Math.floor((normalized - 0.3) * 2.5 * 255);
            b = Math.floor((1 - (normalized - 0.3) * 2.5) * 255);
        } else {
            r = Math.floor((normalized - 0.7) * 3.3 * 255);
            g = Math.floor((1 - (normalized - 0.7) * 3.3) * 255);
        }
        watCtx.fillStyle = `rgb(${r}, ${g}, ${b})`;
        watCtx.fillRect(i * dx, 0, dx + 1, rowHeight);
    }

    requestAnimationFrame(renderSpectrumLoop);
}

function updateOverlayFreqs() {
    const halfBw = state.bandwidthMhz / 2;
    const startFreq = (state.centerFreqMhz - halfBw).toFixed(3);
    const endFreq = (state.centerFreqMhz + halfBw).toFixed(3);

    const left = document.getElementById("overlayFreqLeft");
    const center = document.getElementById("overlayFreqCenter");
    const right = document.getElementById("overlayFreqRight");

    if (left) left.textContent = `${startFreq} MHz`;
    if (center) center.textContent = `CENTER: ${state.centerFreqMhz.toFixed(6)} MHz`;
    if (right) right.textContent = `${endFreq} MHz`;
}

